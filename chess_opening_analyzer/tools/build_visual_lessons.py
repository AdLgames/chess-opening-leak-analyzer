"""Compile factual teaching diagrams from the authored course positions.

No engine score or positional claim is invented: attacks come from python-chess,
and each final explanation is the existing authored lesson note.
"""
import json
from pathlib import Path
import chess

PUBLIC = Path(__file__).resolve().parents[2] / 'chess-dashboard/public'
NAMES = {chess.PAWN:'pawn',chess.KNIGHT:'knight',chess.BISHOP:'bishop',chess.ROOK:'rook',chess.QUEEN:'queen',chess.KING:'king'}
CENTRE = {chess.D4,chess.E4,chess.D5,chess.E5}


def arrow(origin, target, kind='best', knight=False):
    result={'from':chess.square_name(origin),'to':chess.square_name(target),'kind':kind}
    if knight:
        result['via']=chess.square_name(chess.square(chess.square_file(origin),chess.square_rank(target)))
    return result


def build():
    courses=json.loads((PUBLIC/'app/opening-courses.js').read_text().split('window.OpeningCourses = ',1)[1].rstrip(';\n'))
    scenes={}
    for course in courses:
        for card in course['cards']:
            board=chess.Board(card['fen']); move=board.parse_san(card['move']); piece=board.piece_at(move.from_square)
            name=NAMES[piece.piece_type]; origin=chess.square_name(move.from_square); target=chess.square_name(move.to_square)
            castling=board.is_castling(move)
            path=[arrow(move.from_square,move.to_square,knight=piece.piece_type==chess.KNIGHT)]
            text=f'The {name} on {origin} can legally play {card["move"]} in this position. Follow the arrow to {target}.'
            if piece.piece_type==chess.KNIGHT: text+=' Knights jump over other pieces; the L shows the shape of the move.'
            if castling:
                rank=chess.square_rank(move.from_square); kingside=chess.square_file(move.to_square)>chess.square_file(move.from_square)
                rook_from=chess.square(7 if kingside else 0,rank);rook_to=chess.square(5 if kingside else 3,rank)
                path.append(arrow(rook_from,rook_to,'book'))
                text='Castling moves two pieces: the king goes two squares towards the rook, and the rook goes beside it. The position meets the castling rules.'
            first={'fen':board.fen(),'title':'Follow the move' if not castling else 'Two pieces, one move','text':text,'arrows':path,'circles':[{'square':origin,'kind':'book'},{'square':target,'kind':'best'}],'stage':'move'}
            board.push(move)
            attacked=list(board.attacks(move.to_square))
            def priority(sq):
                other=board.piece_at(sq)
                value=({chess.QUEEN:9,chess.ROOK:5,chess.BISHOP:3,chess.KNIGHT:3,chess.PAWN:1,chess.KING:2}.get(other.piece_type,0) if other and other.color!=piece.color else 0)
                return (value,sq in CENTRE,-sq)
            targets=sorted(attacked,key=priority,reverse=True)[:6]
            control_text=f'The circles mark {len(targets)} of the squares attacked by the {name} on {target} in this position.' if len(attacked)>len(targets) else f'The circles mark the squares attacked by the {name} on {target} in this position.'
            if name=='pawn': control_text+=' Pawns attack diagonally; moving forward is different from attacking a square.'
            else: control_text+=' A circled friendly piece is defended. These are attacks, not a promise every capture is legal.'
            second={'fen':board.fen(),'title':'See the board control','text':control_text,'arrows':[arrow(move.to_square,sq,'book',piece.piece_type==chess.KNIGHT) for sq in targets[:2]],'circles':[{'square':chess.square_name(sq),'kind':'book'} for sq in targets],'stage':'control','source':target}
            # Final frame keeps the lesson's checked explanation, with relevant attacks.
            preferred=targets[:2]
            if card['id']=='bishop' and course['id']=='italian-v1': preferred=[chess.F7]
            enemies=[sq for sq in attacked if board.piece_at(sq) and board.piece_at(sq).color!=piece.color]
            is_fork=piece.piece_type==chess.KNIGHT and len(enemies)>=2
            if is_fork: preferred=sorted(enemies,key=priority,reverse=True)[:2]
            final={'fen':board.fen(),'title':'Two targets, one knight' if is_fork else 'Why this move helps','text':card['idea']+' '+card['why'],'arrows':[arrow(move.to_square,sq,'best',piece.piece_type==chess.KNIGHT) for sq in preferred],'circles':[{'square':chess.square_name(sq),'kind':'best'} for sq in preferred],'stage':'idea','source':target}
            scenes[f'{course["id"]}/{card["id"]}']=[first,second,final]
    return scenes


if __name__=='__main__':
    data=build()
    (PUBLIC/'app/visual-lessons.js').write_text('/* Generated by tools/build_visual_lessons.py. Attacks are geometric, not legal-move claims. */\nwindow.VisualLessons = '+json.dumps(data,indent=2)+';\n')
    print(f'{len(data)} visual lessons, {sum(map(len,data.values()))} teaching frames')
